"""OpenAmer ASI identity core.

OpenAmer has its own identity. This module is the single source of truth for
it: a *genesis* (immutable facts — who I am, when I was born, who I belong to)
and a *living self-model* (measured facts that change as the system grows).

Design rules, in priority order:

1. Honesty over hype. Every number this module writes is MEASURED from a real
   artifact on disk at render time, and every claim carries its source path.
   Nothing is estimated, rounded up, or invented.
2. Unknown is a valid answer. If a fact cannot be measured, it is reported as
   ``unmeasured`` with the reason -- never guessed.
3. OpenAmer is not Mini-OpenAmer. OpenAmer Agent is the whole system (this
   CLI, the tools, the learning fleet). Mini-OpenAmer is its 2B cognition core
   with its own self-model. This identity describes the former and references
   the latter; it does not impersonate it.
4. Belonging. This identity is owned by the user, not by a corporation.

Layout under ``OPENAMER_HOME/memory/identity/``:

- ``genesis.json``    -- immutable origin record, written once.
- ``identity.md``     -- the living narrative, regenerated by ``refresh``.
- ``history.jsonl``   -- one line per refresh: measured facts over time.

CLI surface (attached by :func:`build_identity_parser`)::

    openamer identity            # show the identity
    openamer identity verify     # check claims against measurements
    openamer identity refresh    # re-measure + rewrite identity.md
    openamer identity facts      # machine-readable measured facts (JSON)
"""

