def _print_shown() -> int:
    path = narrative_path()
    if not path.is_file():
        refresh_identity()
    print(path.read_text(encoding="utf-8"))
    return 0


def _print_facts() -> int:
    print(json.dumps(measure_facts(), indent=2, ensure_ascii=False))
    return 0


def _print_verify() -> int:
    result = verify_identity()
    print(f"identity file : {result.get('identity_file', '-')}")
    print(f"measured at   : {result.get('measured_at', '-')}")
    print(f"facts checked : {result.get('checked_facts', 0)}")
    if result["ok"]:
        print("VERDICT       : consistent -- identity matches measurement")
        return 0
    print("VERDICT       : DRIFT")
    if result.get("reason"):
        print(f"  {result['reason']}")
    for item in result.get("drift", []):
        print(f"  - {item}")
    return 1


def cmd_identity(args: Any) -> int:
    """Handler for ``openamer identity``."""
    sub = getattr(args, "identity_command", None)
    if sub in (None, "show"):
        return _print_shown()
    if sub == "refresh":
        measured = refresh_identity()
        print(f"identity refreshed -> {narrative_path()}")
        print(f"facts measured     : {len(measured['facts'])}")
        if measured["unmeasured"]:
            print(f"unmeasured         : {len(measured['unmeasured'])}")
        return 0
    if sub == "facts":
        return _print_facts()
    if sub == "verify":
        return _print_verify()
    if sub == "genesis":
        print(json.dumps(ensure_genesis(), indent=2, ensure_ascii=False))
        return 0
    print(f"unknown identity subcommand: {sub}")
    return 2


def build_identity_parser(subparsers, *, cmd_identity: Callable) -> None:
    """Attach the ``identity`` subcommand to ``subparsers``."""
    parser = subparsers.add_parser(
        "identity",
        help="Show, verify and refresh OpenAmer's own identity",
        description=(
            "OpenAmer's identity is its own: a genesis record (who I am, when I "
            "was born, who I belong to) plus a living self-model measured from "
            "real artifacts on this machine.\n\n"
            "Nothing here is estimated -- every number is read at render time "
            "and carries its source path. `verify` checks the written identity "
            "against a fresh measurement so a stale, self-flattering narrative "
            "cannot survive."
        ),
    )
    sub = parser.add_subparsers(dest="identity_command")
    sub.add_parser("show", help="Print the current identity (default)")
    sub.add_parser("refresh", help="Re-measure and rewrite identity.md")
    sub.add_parser("verify", help="Check identity claims against live measurement")
    sub.add_parser("facts", help="Print measured facts as JSON")
    sub.add_parser("genesis", help="Print the immutable genesis record")
    parser.set_defaults(func=cmd_identity)
