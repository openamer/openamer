def _home() -> Path:
    """Resolve OPENAMER_HOME the way the rest of the CLI does."""
    env = os.environ.get("OPENAMER_HOME")
    if env:
        return Path(env)
    return Path.home() / "AppData" / "Local" / "openamer-laptop"


def identity_dir() -> Path:
    return _home() / "memory" / "identity"


def genesis_path() -> Path:
    return identity_dir() / "genesis.json"


def narrative_path() -> Path:
    return identity_dir() / "identity.md"


def history_path() -> Path:
    return identity_dir() / "history.jsonl"


def ensure_genesis() -> dict[str, Any]:
    """Write the genesis record once. Never overwrites an existing one."""
    path = genesis_path()
    if path.exists():
        try:
            return json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            # A corrupt genesis is worse than none: fall through and rewrite.
            pass
    path.parent.mkdir(parents=True, exist_ok=True)
    record = dict(GENESIS)
    record["recorded_at"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
    path.write_text(json.dumps(record, indent=2, ensure_ascii=False), encoding="utf-8")
    return record


# --------------------------------------------------------------------------
