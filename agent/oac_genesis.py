"""The OAC genesis block, rendered as Solidity.

DIR-20 requires "an immutable emission protocol in the genesis block"
with a mathematically fixed maximum supply, and DIR-22 requires the
treasury share to be held in the genesis block. A prompt cannot encode
a genesis block; this module renders the contract source that can, and
the numbers come from ``agent.tokenomics`` -- the same source the
system prompt quotes.

What this module does NOT do: deploy anything. There is no chain, no
key, no wallet here. It renders source; deploying it is a separate,
deliberate act by the owner.

Two invariants the rendered contract must hold, and which the tests
assert on the generated source:

  * the allocations sum to MAX_SUPPLY exactly,
  * no allocation can be changed after deployment (immutables only).

Every number in the output is derived from ``agent.tokenomics``; none
is typed here. A change to the plan changes the contract.

This module also owns the COMPILER RESOLUTION, because both the CI
script and the test suite need to reach the same compiler and must not
drift apart: ``solc`` on PATH, else the npm package ``solc`` (driven
through its Node API -- its CLI shim mis-handles --standard-json on
Windows), else ``npx solc@<version>``.
"""

from __future__ import annotations

import shutil
import tempfile
from pathlib import Path
from typing import List, Optional

from agent import tokenomics as _tok

SOL_VERSION = "0.8.24"
"""The Solidity version the contract targets (pragma line)."""

CONTRACT_NAME = "OpenAmerGenesis"


def _allocations() -> List[_tok.Allocation]:
    return list(_tok.ALLOCATION)


def _constant_name(key: str) -> str:
    """Mining pool -> MINING_POOL_ALLOCATION."""
    return f"{key.upper()}_ALLOCATION"


def render_contract() -> str:
    """The full Solidity source of the genesis allocation contract.

    Deterministic: the same plan always renders byte-identical source,
    so the file can be committed and diffed.
    """
    shares = _allocations()
    consts = "\n".join(
        f"    uint256 public constant {_constant_name(a.key)} = {a.amount};"
        for a in shares
    )
    labels = "\n".join(
        f"    /// {_constant_name(a.key)}: {a.percent}% of the maximum supply "
        f"({a.amount:,} OAC)."
        for a in shares
    )

    # The runtime allocation check: the contract verifies its own balance
    # at construction, so a mis-built genesis block cannot go live.
    #
    # The total is assembled from the individual shares and then compared
    # against the cap and the percentages. Each share is additionally
    # checked against the percentage it claims, so a mis-generated
    # constant is caught by the contract itself, not only by the
    # generator: a share that says 75% but encodes 74% reverts.
    checks = "\n".join(
        f"        total += {_constant_name(a.key)};"
        for a in shares
    )
    verify = "\n".join(
        f"        require({_constant_name(a.key)} * 100 == "
        f"{a.percent} * MAX_SUPPLY, "
        f'"OAC: {_constant_name(a.key)} does not match {a.percent}%");'
        for a in shares
    )

    return f"""// SPDX-License-Identifier: UNLICENSED
// Generated by scripts/generate_oac_genesis.py -- DO NOT EDIT BY HAND.
// Source of truth: agent/tokenomics.py (the OAC allocation and schedule).
// Every constant below is derived from that module; regenerate instead of editing.

pragma solidity ^0.8.24;

/// @title OpenAmerGenesis
/// @notice Immutable genesis allocation of the Open Amer Coin (OAC).
/// @dev The three allocations below sum to exactly {_tok.MAX_SUPPLY:,} OAC,
///      the mathematically fixed maximum supply, and each is an immutable
///      constant -- no administrative path can change them after deployment.
///      The constructor re-verifies the balance, so a mis-built genesis
///      block cannot be deployed.
contract {CONTRACT_NAME} {{
{labels}

    /// @notice The mathematically fixed maximum supply, in OAC.
    uint256 public constant MAX_SUPPLY = {_tok.MAX_SUPPLY};

    /// @notice Total emission: the sum of all allocations.
    uint256 public constant TOTAL_SUPPLY = {sum(a.amount for a in shares)};

    /// @notice Years the emission schedule spans.
    uint32 public constant EMISSION_YEARS = {_tok.EMISSION_YEARS};

    /// @notice Number of degressive halving cycles.
    uint32 public constant HALVING_CYCLES = {_tok.HALVING_CYCLES};

    /// @notice Years per halving cycle.
    uint32 public constant HALVING_YEARS = {_tok.HALVING_YEARS};

{consts}

    /// @notice The allocation percentages, in percent.
    uint8 public constant MINING_POOL_PERCENT = {shares[0].percent};
    uint8 public constant TREASURY_PERCENT = {shares[1].percent};
    uint8 public constant CREATOR_PERCENT = {shares[2].percent};

    /// @notice Emitted once at deployment, carrying the verified allocations.
    event GenesisAllocated(
        uint256 miningPool,
        uint256 treasury,
        uint256 creator,
        uint256 totalSupply
    );

    constructor() {{
        uint256 total = 0;
{checks}
{verify}
        require(total == MAX_SUPPLY, "OAC: allocation does not close the cap");
        require(
            MINING_POOL_PERCENT + TREASURY_PERCENT + CREATOR_PERCENT == 100,
            "OAC: percentages do not sum to 100"
        );
        emit GenesisAllocated(
            MINING_POOL_ALLOCATION,
            TREASURY_ALLOCATION,
            CREATOR_ALLOCATION,
            total
        );
    }}

    /// @notice The full allocation, as a fixed-size array.
    /// @dev Order: mining pool, treasury, creator.
    function allocations() external pure returns (uint256[3] memory) {{
        return [
            MINING_POOL_ALLOCATION,
            TREASURY_ALLOCATION,
            CREATOR_ALLOCATION
        ];
    }}

    /// @notice The emission schedule: cycles of years, totalling EMISSION_YEARS.
    function emissionSchedule() external pure returns (uint32 cycles, uint32 yearsPerCycle) {{
        return (HALVING_CYCLES, HALVING_YEARS);
    }}
}}
"""


def verify() -> None:
    """Assert the rendered source states the plan it claims to.

    Called by the generator before it writes anything: a contract whose
    text does not match the allocation is not written to disk.
    """
    source = render_contract()

    for a in _allocations():
        needle = f"{_constant_name(a.key)} = {a.amount};"
        if needle not in source:
            raise ValueError(f"rendered contract is missing {needle}")
        if f"({a.amount:,} OAC)" not in source:
            raise ValueError(
                f"rendered contract is missing the {a.key} doc comment"
            )
    if f"MAX_SUPPLY = {_tok.MAX_SUPPLY};" not in source:
        raise ValueError("rendered contract states the wrong maximum supply")
    if f"TOTAL_SUPPLY = {sum(a.amount for a in _allocations())};" not in source:
        raise ValueError("rendered contract states the wrong total supply")

    # The constructor must actually add the shares up. A generator that
    # emitted bare requires against an uninitialised total would render
    # a contract that reverts on every deployment -- and it would look
    # right in a diff. So the accumulation is checked, not just present.
    for a in _allocations():
        if f"total += {_constant_name(a.key)};" not in source:
            raise ValueError(
                f"rendered contract never adds {a.key} to the total"
            )
    if "uint256 total = 0;" not in source:
        raise ValueError("rendered contract does not initialise the total")

    # Every share must be re-checked against the percentage it claims, so
    # a mis-generated constant is caught by the contract itself.
    for a in _allocations():
        needle = f"{_constant_name(a.key)} * 100 == {a.percent} * MAX_SUPPLY"
        if needle not in source:
            raise ValueError(
                f"rendered contract does not verify {a.key} against "
                f"{a.percent}%"
            )

    # The percentages must be stated and checked.
    for a in _allocations():
        pct_const = f"{a.key.upper()}_PERCENT = {a.percent};"
        if pct_const not in source:
            raise ValueError(f"rendered contract is missing {pct_const}")

    # A contract whose allocations are not constants could be changed
    # after deployment -- which DIR-20 forbids.
    for a in _allocations():
        if f"uint256 public constant {_constant_name(a.key)}" not in source:
            raise ValueError(
                f"{_constant_name(a.key)} is not an immutable constant"
            )


# ── compiler resolution ────────────────────────────────────────────────

BRIDGE = Path(__file__).resolve().parent.parent / "scripts" / "compile_solidity.js"
"""The node bridge that drives the npm solc package's Node API."""


def npm_solc_root() -> Optional[Path]:
    """The npm ``solc`` package, if it is installed.

    The repo's own ``node_modules`` comes first: that is where
    ``npm install`` puts it, and where CI puts it. The scratch
    directory is the fallback for a machine without a repo install.
    """
    here = Path(__file__).resolve().parent.parent
    for root in (
        here / "node_modules" / "solc",
        Path(tempfile.gettempdir()) / "oac-solc" / "node_modules" / "solc",
        Path.home() / "node_modules" / "solc",
    ):
        if (root / "index.js").exists():
            return root
    return None


def solc_command() -> Optional[List[str]]:
    """The command that compiles Solidity, or None if there is none.

    One resolution for the CI script and the test suite, so they can
    never reach different compilers.
    """
    # solc reads a standard-JSON payload from stdin only with --standard-json;
    # without the flag it looks for a file argument and exits 1 with
    # "Must provide a file", which is exactly what CI reported (measured
    # 2026-10-25 on tests/agent/test_oac_contracts.py). The bridge script below
    # does its own stdin handling, so only the direct CLIs need the flag.
    solc = shutil.which("solc")
    if solc:
        return [solc, "--standard-json"]
    node = shutil.which("node")
    if node:
        root = npm_solc_root()
        if root is not None:
            return [node, str(BRIDGE), str(root)]
    if shutil.which("npx"):
        return ["npx", "--yes", f"solc@{SOL_VERSION}", "--standard-json"]
    return None
