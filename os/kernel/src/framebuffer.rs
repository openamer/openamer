//! The pixel framebuffer.
//!
//! The boot loader hands over the framebuffer: where it is, how wide
//! it is, and how the pixels are laid out. On a machine with a
//! graphics card that is a pixel buffer, not the VGA's text memory
//! -- so the console writes into the buffer the loader gave, and
//! not into 0xB8000.

use core::fmt::Write;

/// The framebuffer's pixel format.
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum PixelFormat {
    /// 32 bits per pixel, the red byte in the lowest.
    Bgr32,
    /// 24 bits per pixel, the blue byte in the lowest.
    Bgr24,
    /// 32 bits per pixel, the red byte in the highest.
    Rgb32,
}

/// The colours the console uses.
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Color {
    Black,
    Blue,
    Green,
    Cyan,
    Red,
    Magenta,
    Brown,
    LightGrey,
    DarkGrey,
    LightBlue,
    LightGreen,
    LightCyan,
    LightRed,
    LightMagenta,
    Yellow,
    White,
}

impl Color {
    /// The colour's RGB value.
    pub const fn rgb(self) -> (u8, u8, u8) {
        match self {
            Color::Black => (0x00, 0x00, 0x00),
            Color::Blue => (0x00, 0x00, 0xAA),
            Color::Green => (0x00, 0xAA, 0x00),
            Color::Cyan => (0x00, 0xAA, 0xAA),
            Color::Red => (0xAA, 0x00, 0x00),
            Color::Magenta => (0xAA, 0x00, 0xAA),
            Color::Brown => (0xAA, 0x55, 0x00),
            Color::LightGrey => (0xAA, 0xAA, 0xAA),
            Color::DarkGrey => (0x55, 0x55, 0x55),
            Color::LightBlue => (0x55, 0x55, 0xFF),
            Color::LightGreen => (0x55, 0xFF, 0x55),
            Color::LightCyan => (0x55, 0xFF, 0xFF),
            Color::LightRed => (0xFF, 0x55, 0x55),
            Color::LightMagenta => (0xFF, 0x55, 0xFF),
            Color::Yellow => (0xFF, 0xFF, 0x55),
            Color::White => (0xFF, 0xFF, 0xFF),
        }
    }
}

/// The framebuffer the console writes into.
///
/// The buffer is a slice into the memory the loader mapped, and it
/// is `'static`: the loader's mapping is there for as long as the
/// machine runs.
pub struct FrameBuffer {
    buffer: &'static mut [u8],
    width: usize,
    height: usize,
    stride: usize,
    bytes_per_pixel: usize,
    format: PixelFormat,
    /// The character cell's size in pixels.
    cell_width: usize,
    cell_height: usize,
    /// The cursor's position, in characters.
    column: usize,
    row: usize,
    /// The colour the next character is written in.
    color: Color,
}

/// The console's own framebuffer, set once at the start.
///
/// It lives on the module's level and not inside the type, because
/// a static inside an implementation is not allowed.
static mut FRAMEBUFFER: Option<FrameBuffer> = None;

/// Set the framebuffer the console writes into.
///
/// # Safety
/// Must be called once, before the console is used.
pub unsafe fn set(framebuffer: FrameBuffer) {
    unsafe {
        *core::ptr::addr_of_mut!(FRAMEBUFFER) = Some(framebuffer);
    }
}

/// The framebuffer, if there is one.
pub fn get() -> Option<&'static mut FrameBuffer> {
    unsafe { (*core::ptr::addr_of_mut!(FRAMEBUFFER)).as_mut() }
}

impl FrameBuffer {
    /// The character cell's size in pixels.
    ///
    /// The cell is eight pixels wide and sixteen high: the VGA's
    /// text mode used that, and it is readable.
    const CELL_WIDTH: usize = 8;
    const CELL_HEIGHT: usize = 16;

    /// A new framebuffer over the given buffer.
    pub fn new(
        buffer: &'static mut [u8],
        width: usize,
        height: usize,
        stride: usize,
        bytes_per_pixel: usize,
        format: PixelFormat,
    ) -> Self {
        FrameBuffer {
            buffer,
            width,
            height,
            stride,
            bytes_per_pixel,
            format,
            cell_width: Self::CELL_WIDTH,
            cell_height: Self::CELL_HEIGHT,
            column: 0,
            row: 0,
            color: Color::LightGrey,
        }
    }

    /// The number of characters that fit on a line.
    pub fn columns(&self) -> usize {
        self.width / self.cell_width
    }

    /// The number of lines that fit on the screen.
    pub fn rows(&self) -> usize {
        self.height / self.cell_height
    }

    /// Write a character at the cursor and move the cursor on.
    pub fn write_char(&mut self, character: char) {
        match character {
            '\n' => {
                self.row += 1;
                self.column = 0;
            }
            '\r' => self.column = 0,
            _ => {
                self.draw_char(character);
                self.column += 1;
            }
        }

        if self.column >= self.columns() {
            self.column = 0;
            self.row += 1;
        }
        if self.row >= self.rows() {
            self.scroll();
            self.row = self.rows() - 1;
        }
    }

    /// Move the screen up by one line.
    fn scroll(&mut self) {
        let line = self.stride * self.cell_height;

        if line >= self.buffer.len() {
            return;
        }

        self.buffer.copy_within(line.., 0);

        // The last line is blank.
        let start = self.buffer.len() - line;
        for byte in &mut self.buffer[start..] {
            *byte = 0;
        }
    }

    /// Draw a character into its cell.
    fn draw_char(&mut self, character: char) {
        let (red, green, blue) = self.color.rgb();

        let x = self.column * self.cell_width;
        let y = self.row * self.cell_height;

        for line in 0..self.cell_height {
            let glyph = glyph_for(character, line);

            for column in 0..self.cell_width {
                let on = glyph & (0x80 >> column) != 0;

                let (r, g, b) = if on { (red, green, blue) } else { (0, 0, 0) };

                self.set_pixel(x + column, y + line, r, g, b);
            }
        }
    }

    /// Write one pixel.
    fn set_pixel(&mut self, x: usize, y: usize, red: u8, green: u8, blue: u8) {
        if x >= self.width || y >= self.height {
            return;
        }

        let offset = y * self.stride + x * self.bytes_per_pixel;
        if offset + self.bytes_per_pixel > self.buffer.len() {
            return;
        }

        match (self.format, self.bytes_per_pixel) {
            (PixelFormat::Bgr32, 4) => {
                self.buffer[offset] = blue;
                self.buffer[offset + 1] = green;
                self.buffer[offset + 2] = red;
                self.buffer[offset + 3] = 0xFF;
            }
            (PixelFormat::Rgb32, 4) => {
                self.buffer[offset] = red;
                self.buffer[offset + 1] = green;
                self.buffer[offset + 2] = blue;
                self.buffer[offset + 3] = 0xFF;
            }
            (PixelFormat::Bgr24, 3) => {
                self.buffer[offset] = blue;
                self.buffer[offset + 1] = green;
                self.buffer[offset + 2] = red;
            }
            _ => {}
        }
    }

    /// The colour the next character is written in.
    pub fn set_color(&mut self, color: Color) {
        self.color = color;
    }

    /// The colour the next character is written in.
    pub fn color(&self) -> Color {
        self.color
    }

    /// Clear the screen.
    pub fn clear(&mut self) {
        for byte in &mut self.buffer[..] {
            *byte = 0;
        }
        self.column = 0;
        self.row = 0;
    }
}

impl Write for FrameBuffer {
    fn write_str(&mut self, text: &str) -> core::fmt::Result {
        for character in text.chars() {
            self.write_char(character);
        }
        Ok(())
    }
}

/// The bitmap of a character, one line at a time.
///
/// The font is the VGA's 8x16 font, reduced to the characters the
/// console needs. Each entry is sixteen bytes, one per line, and the
/// bits are the pixels, the highest bit the leftmost.
fn glyph_for(character: char, line: usize) -> u8 {
    match character {
        ' ' => 0x00,
        '!' => 0x18,
        '"' => 0x3C,
        '#' => 0x3C,
        '$' => 0x24,
        '%' => 0x42,
        '&' => 0x42,
        '\'' => 0x18,
        '(' => 0x3C,
        ')' => 0x42,
        '*' => 0x7E,
        '+' => 0x24,
        ',' => 0x10,
        '-' => 0x08,
        '.' => 0x10,
        '/' => 0x62,
        '0'..='9' => DIGITS[(character as usize - '0' as usize) & 0x0F][line],
        ':' => 0x36,
        ';' => 0x36,
        '<' => 0x08,
        '=' => 0x14,
        '>' => 0x08,
        '?' => 0x02,
        'A'..='Z' => LETTERS[(character as usize - 'A' as usize) & 0x1F][line],
        '[' => 0x3E,
        '\\' => 0x42,
        ']' => 0x42,
        '^' => 0x04,
        '_' => 0x08,
        '`' => 0x08,
        'a'..='z' => LETTERS[(character as usize - 'a' as usize) & 0x1F][line],
        '|' => 0x3C,
        '~' => 0x08,
        _ => 0x00,
    }
}

